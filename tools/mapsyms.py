#!/usr/bin/env python3
"""Turn WSROOT.MAP (the 1983 linker's load map) into a C header of symbols.

    python3 -I tools/mapsyms.py WSROOT.MAP > src/core/sw_symbols.h

The map is in https://github.com/historicalsource/star-wars (WSROOT.MAP).
It belongs to the 22-June-1983 program, MAME's "starwars1": every RAM
variable, I/O address and VG constant the port refers to comes from here,
under its original name ('.' becomes '_', '$' becomes 'S').
"""
import re
import sys


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    raw = open(sys.argv[1], "rb").read()
    text = raw.replace(b"\r", b"\n").replace(b"\f", b"\n").replace(b"\0", b"").decode("ascii", "replace")
    syms = {}
    # Entries look like "NAME    ADDR     MODULE MODULE ... #"
    for m in re.finditer(r"([A-Z0-9$.]{1,6})\s+([0-9A-F]{4})\s+(?=[A-Z])", text):
        syms.setdefault(m.group(1), int(m.group(2), 16))

    print("/* sw_symbols.h - generated by tools/mapsyms.py from WSROOT.MAP")
    print(" * (the load map of the 22-June-1983 program, MAME \"starwars1\").")
    print(" * Original names: '.' -> '_', '$' -> 'S'. Do not edit. */")
    print("#ifndef SWVP_SW_SYMBOLS_H")
    print("#define SWVP_SW_SYMBOLS_H")
    print()
    seen = set()
    for name in sorted(syms):
        c = "SW_" + name.replace(".", "_").replace("$", "S")
        if c in seen:
            continue
        seen.add(c)
        print("#define %-14s 0x%04X" % (c, syms[name]))
    print()
    print("#endif")


if __name__ == "__main__":
    main()
